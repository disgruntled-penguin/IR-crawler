#!/bin/bash
# Builds the course submission folder and ZIP from committed files only: report PDF, GitHub link, source code, dataset.
# NAME=CSD358_Member1_Member2_Member3 bash scripts/make_submission.sh
set -eu
cd "$(dirname "$0")/.."
NAME=${NAME:-CSD358_NishitaKadali_PustakPathak}
OUT=submission
STAGE=$OUT/$NAME
[ -e "$STAGE" ] && { echo "$STAGE exists; move it away first"; exit 1; }
mkdir -p "$STAGE/source_code" "$STAGE/dataset"

cp report/SpinTrace_final_report.pdf "$STAGE/"
git remote get-url origin | sed 's#\.git$##' > "$STAGE/GITHUB_LINK.txt"
git archive HEAD spintrace scripts tests seeds report README.md requirements.txt PROGRESS.md | tar -x -C "$STAGE/source_code"
git archive HEAD evaldata results | tar -x -C "$STAGE/dataset"

cat > "$STAGE/dataset/DATASET.md" <<'EOF'
# Dataset used by SpinTrace

Full description with counts: results/dataset.md (generated by `python -m spintrace.eval.dataset_stats`) and Section 6.1
of the report. Everything here is committed to the repository.

| Path | What it is |
| --- | --- |
| evaldata/wikinews.jsonl | English Wikinews originals (CC BY 2.5, Wikinews contributors) used as freely licensed sources |
| evaldata/rewrites.jsonl | graded rewrites of the originals: exact, light, synonym, SEO, summary, round-trip translation, facts-only |
| evaldata/rewrites_xl.jsonl | Hindi, Tamil, Telugu and Bengali translations, Hindi SEO rewrites, summaries and same-event articles, back-translations and LLM mashups (generated locally with Gemma 3 4B) |
| evaldata/mashups.jsonl, formats.jsonl | rule-based mashups and reformatted articles |
| evaldata/hard_negatives.csv | same-event articles from different outlets, mined from the crawl (URLs and scores) |
| evaldata/newsguard_pairs.csv | NewsGuard-documented farm pairs (Wayback links) |
| evaldata/live_*.csv, search_judgments.csv | live detections and the judged labels (URLs and scores, no article text) |
| evaldata/crawl_urls.csv, crawl_minhash.npz | every crawled URL with its metadata and MinHash signature |
| results/ | every table and chart the report uses |

Crawled article texts are not included. They are third-party content, which we do not redistribute, and the crawl database
is several gigabytes. `crawl_urls.csv` lists every crawled page, and `python -m spintrace recrawl` rebuilds the texts from the
live web (see the README); the numbers in `results/` were produced on our crawl of 6 October to 22 November 2026.
EOF

(cd "$OUT" && zip -r -q "$NAME.zip" "$NAME")
echo "built $OUT/$NAME.zip"
unzip -l "$OUT/$NAME.zip" | tail -1
ls -1 "$STAGE"
