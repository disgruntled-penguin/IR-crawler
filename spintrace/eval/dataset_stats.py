"""Dataset summary for the report: what is in the store, where it came from, and what each label file holds.

Run as `python -m spintrace.eval.dataset_stats`. It reads the database read-only (the crawler may be
writing) and the label files in evaldata/, and writes results/dataset.md and results/dataset.json.
"""
import json
import sqlite3
import statistics
from collections import Counter, defaultdict
from datetime import datetime, timezone

from .. import config

SCRIPT_NAMES = {"latn": "Latin (English)", "deva": "Devanagari (Hindi, Marathi)", "taml": "Tamil", "telu": "Telugu",
                "beng": "Bengali", "gujr": "Gujarati", "guru": "Gurmukhi (Punjabi)"}
FILES = {
    "wikinews.jsonl": "Wikinews originals (title, URL, publish time, text, licence)",
    "rewrites.jsonl": "English graded rewrites of the originals, with the generator and the level",
    "rewrites_xl.jsonl": "Hindi, Tamil, Telugu and Bengali rewrites, back-translations and LLM mashups",
    "mashups.jsonl": "Splice mashups with exact source shares",
    "formats.jsonl": "Listicle and Q&A reformattings of originals",
    "hard_negatives.csv": "Same-event pairs from different outlets that share no text",
    "live_flagged.csv": "Flagged live pairs with the two judges' labels",
    "search_judgments.csv": "Judged live search results",
    "newsguard_pairs.csv": "NewsGuard-documented farm pairs with Wayback links",
    "crawl_urls.csv": "URLs of crawled articles (no texts)",
}


def day(t):
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d") if t else "-"


def file_rows(path):
    if path.suffix == ".jsonl":
        with path.open() as f:
            rows = [json.loads(l) for l in f if l.strip()]
        return len(rows), Counter(r.get("level") for r in rows if r.get("level"))
    with path.open() as f:
        return max(0, sum(1 for _ in f) - 1), Counter()


def collect():
    con = sqlite3.connect(f"file:{config.DB_PATH}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    by_origin = defaultdict(lambda: {"n": 0, "words": [], "first": None, "last": None})
    crawl_scripts, crawl_sites, crawl_dates = Counter(), Counter(), Counter()
    for r in con.execute("SELECT origin, site, published, fetched_at, n_words, meta FROM docs"):
        o = by_origin[r["origin"]]
        o["n"] += 1
        o["words"].append(r["n_words"] or 0)
        if r["origin"] == "crawl":
            script = json.loads(r["meta"] or "{}").get("script", "latn")
            crawl_scripts[script] += 1
            crawl_sites[r["site"]] += 1
            crawl_dates[day(r["fetched_at"])] += 1
            if r["fetched_at"]:
                o["first"] = min(o["first"] or r["fetched_at"], r["fetched_at"])
                o["last"] = max(o["last"] or r["fetched_at"], r["fetched_at"])
    requests = con.execute("SELECT COUNT(*) FROM fetch_log WHERE event='fetch'").fetchone()[0]
    return by_origin, crawl_scripts, crawl_sites, crawl_dates, requests


def main():
    by_origin, scripts, sites, dates, requests = collect()
    out = {"origins": {}, "crawl_scripts": dict(scripts), "crawl_sites": len(sites), "fetch_requests": requests,
           "crawl_days": dict(sorted(dates.items())), "files": {}}
    lines = ["# Dataset summary", "", "Generated by `python -m spintrace.eval.dataset_stats`.", "",
             "## Documents in the store", "", "| Origin | Documents | Median words | Crawled between |",
             "| --- | --- | --- | --- |"]
    for origin, o in sorted(by_origin.items(), key=lambda kv: -kv[1]["n"]):
        med = int(statistics.median(o["words"])) if o["words"] else 0
        span = f"{day(o['first'])} to {day(o['last'])}" if o["first"] else "-"
        out["origins"][origin] = {"n": o["n"], "median_words": med}
        lines.append(f"| {origin} | {o['n']:,} | {med} | {span} |")
    lines += ["", f"Crawled articles come from {len(sites)} sites; {requests:,} fetch requests are logged.", "",
              "## Crawled articles by script", "", "| Script | Articles |", "| --- | --- |"]
    for s, n in scripts.most_common():
        lines.append(f"| {SCRIPT_NAMES.get(s, s)} | {n:,} |")
    lines += ["", "## Crawled articles per day (UTC)", "", "| Day | Articles |", "| --- | --- |"]
    lines += [f"| {d} | {n:,} |" for d, n in sorted(dates.items())]
    lines += ["", "## Label and evaluation files (evaldata/)", "", "| File | Rows | Content |", "| --- | --- | --- |"]
    for name, what in FILES.items():
        path = config.ROOT / "evaldata" / name
        if not path.exists():
            continue
        n, levels = file_rows(path)
        out["files"][name] = {"rows": n, "levels": dict(levels)}
        lines.append(f"| {name} | {n:,} | {what} |")
    for name in ("rewrites.jsonl", "rewrites_xl.jsonl"):
        levels = out["files"].get(name, {}).get("levels")
        if levels:
            lines += ["", f"Levels in {name}: " + ", ".join(f"{k} {v}" for k, v in sorted(levels.items())) + "."]
    config.RESULTS.mkdir(exist_ok=True)
    (config.RESULTS / "dataset.md").write_text("\n".join(lines) + "\n")
    (config.RESULTS / "dataset.json").write_text(json.dumps(out, indent=1))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
